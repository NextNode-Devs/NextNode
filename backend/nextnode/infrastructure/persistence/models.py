class MessageModel(models.Model):
    conversation = models.ForeignKey(ConversationModel, on_delete=models.CASCADE, related_name="messages")
    author = models.ForeignKey(AccountModel, on_delete=models.PROTECT, related_name="messages")
    body = models.TextField(max_length=4000)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "message"
        indexes = (models.Index(fields=["conversation", "id"], name="message_conversation_id_idx"),)
        constraints = (models.CheckConstraint(condition=~Q(body=""), name="message_body_not_empty"),)

    def __str__(self) -> str:
        return f"message {self.id}"


class LeadCandidacyModel(models.Model):
    """A lead application or invitation (#4). ``project_id`` becomes a foreign
    key when #3's Project model exists."""

    class Kind(models.TextChoices):
        APPLICATION = "application"
        INVITATION = "invitation"

    class Status(models.TextChoices):
        INVITED = "invited"
        CANDIDATE = "candidate"
        HIRED = "hired"
        DECLINED = "declined"
        WITHDRAWN = "withdrawn"
        CLOSED = "closed"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    project_id = models.BigIntegerField(db_index=True)
    client = models.ForeignKey(AccountModel, on_delete=models.PROTECT, related_name="lead_invitations_sent")
    developer = models.ForeignKey(AccountModel, on_delete=models.PROTECT, related_name="lead_candidacies")
    kind = models.CharField(max_length=16, choices=Kind.choices)
    status = models.CharField(max_length=16, choices=Status.choices)
    note = models.TextField(max_length=1000, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    decided_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = "lead_candidacy"
        constraints = (
            # Two concurrent hires cannot both be stored: the second one fails here.
            models.UniqueConstraint(
                fields=["project_id"], condition=Q(status="hired"), name="lead_candidacy_one_hire_per_project"
            ),
            models.UniqueConstraint(
                fields=["project_id", "developer"],
                condition=Q(status__in=["invited", "candidate"]),
                name="lead_candidacy_one_open_per_developer",
            ),
        )

    def __str__(self) -> str:
        return f"{self.kind} {self.id} ({self.status})"


class ProjectModel(models.Model):
    """A client brief or a developer idea (#3). The budget is a proposal, in
    whole CAD cents, and exists only on client projects."""

    class Kind(models.TextChoices):
        CLIENT = "client"
        DEVELOPER = "developer"

    class Status(models.TextChoices):
        POSTED = "Posted"
        OFFER_SENT = "OfferSent"
        ASSIGNED = "Assigned"
        IN_PROGRESS = "InProgress"
        COMPLETED = "Completed"
        ARCHIVED = "Archived"

    kind = models.CharField(max_length=16, choices=Kind.choices)
    owner = models.ForeignKey(AccountModel, on_delete=models.PROTECT, related_name="owned_projects")
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.POSTED, db_index=True)
    title = models.CharField(max_length=100)
    description = models.TextField(max_length=5000)
    tech_stack = models.ManyToManyField(SkillModel, related_name="projects", db_table="project_skill")
    target_delivery_date = models.DateField()
    proposed_budget_cents = models.PositiveIntegerField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    deleted_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = "project"
        constraints = (
            models.CheckConstraint(condition=Q(kind__in=["client", "developer"]), name="project_kind_valid"),
            # Ideas never carry a budget; briefs always do, at least CAD 1,500.00.
            models.CheckConstraint(
                condition=Q(kind="developer", proposed_budget_cents__isnull=True)
                | Q(kind="client", proposed_budget_cents__gte=150_000),
                name="project_budget_matches_kind",
            ),
            models.CheckConstraint(
                condition=Q(kind="client") | ~Q(status__in=["OfferSent", "Assigned"]),
                name="project_idea_never_offered",
            ),
        )

    def __str__(self) -> str:
        return f"{self.kind} project {self.id}: {self.title}"


class TeamModel(models.Model):
    """One team per project and one project per team (#3). #5 sets the size
    and adds members."""

    class Status(models.TextChoices):
        OPEN = "open"
        LOCKED = "locked"
        ACTIVE = "active"
        ARCHIVED = "archived"

    project = models.OneToOneField(ProjectModel, on_delete=models.PROTECT, related_name="team")
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.OPEN)
    team_size = models.PositiveSmallIntegerField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    deleted_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = "team"
        constraints = (
            models.CheckConstraint(
                condition=Q(team_size__isnull=True) | Q(team_size__gte=5, team_size__lte=7),
                name="team_size_5_to_7",
            ),
        )

    def __str__(self) -> str:
        return f"team {self.id} ({self.status})"


class TeamMembershipModel(models.Model):
    """Who is on a team (class diagram ``TeamMembership``). Only ``approved``
    rows count; the Lead's row has role ``lead``."""

    class Role(models.TextChoices):
        LEAD = "lead"
        MEMBER = "member"

    class Status(models.TextChoices):
        PENDING = "pending"
        APPROVED = "approved"
        REJECTED = "rejected"

    team = models.ForeignKey(TeamModel, on_delete=models.CASCADE, related_name="memberships")
    account = models.ForeignKey(AccountModel, on_delete=models.PROTECT, related_name="team_memberships")
    role = models.CharField(max_length=16, choices=Role.choices)
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.APPROVED)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "team_membership"
        constraints = (
            models.UniqueConstraint(fields=["team", "account"], name="team_membership_once"),
            models.UniqueConstraint(
                fields=["team"], condition=Q(role="lead"), name="team_membership_one_lead"
            ),
        )

    def __str__(self) -> str:
        return f"{self.account_id} {self.role} of team {self.team_id} ({self.status})"


class TeamCandidacyModel(models.Model):
    """An application to join a team or the Lead's invitation (#5). Accepted, it
    adds the developer's approved ``TeamMembershipModel`` row; until then they
    are not on the team. Keyed by project: one team per project."""

    class Kind(models.TextChoices):
        APPLICATION = "application"
        INVITATION = "invitation"

    class Status(models.TextChoices):
        PENDING = "pending"
        ACCEPTED = "accepted"
        REJECTED = "rejected"
        WITHDRAWN = "withdrawn"
        DECLINED = "declined"
        CLOSED = "closed"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    project = models.ForeignKey(ProjectModel, on_delete=models.PROTECT, related_name="team_candidacies")
    lead = models.ForeignKey(AccountModel, on_delete=models.PROTECT, related_name="team_candidacies_led")
    developer = models.ForeignKey(AccountModel, on_delete=models.PROTECT, related_name="team_candidacies")
    kind = models.CharField(max_length=16, choices=Kind.choices)
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.PENDING)
    closed_reason = models.CharField(max_length=200, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    decided_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = "team_candidacy"
        constraints = (
            models.UniqueConstraint(
                fields=["project", "developer"],
                condition=Q(status="pending"),
                name="team_candidacy_one_pending_per_developer",
            ),
            # Once per team, whatever became of the application.
            models.UniqueConstraint(
                fields=["project", "developer"],
                condition=Q(kind="application"),
                name="team_candidacy_one_application_per_developer",
            ),
        )

    def __str__(self) -> str:
        return f"{self.kind} {self.id} ({self.status})"


class RequirementDocumentModel(models.Model):
    """A private PDF/DOCX on a client project (#3). The bytes live in
    ``FileStorage`` under ``storage_key``; ``filename`` is for display only."""

    class Type(models.TextChoices):
        PDF = "pdf"
        DOCX = "docx"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    project = models.ForeignKey(ProjectModel, on_delete=models.PROTECT, related_name="documents")
    storage_key = models.CharField(max_length=64, unique=True)
    filename = models.CharField(max_length=200)
    type = models.CharField(max_length=8, choices=Type.choices)
    size_bytes = models.PositiveIntegerField()
    uploaded_by = models.ForeignKey(AccountModel, on_delete=models.PROTECT, related_name="uploaded_documents")
    uploaded_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "requirement_document"
        ordering = ("uploaded_at", "id")

    def __str__(self) -> str:
        return self.filename


