    class Meta:
        db_table = "portfolio_project"
        ordering = ("position",)
        constraints = (
            models.UniqueConstraint(
                fields=["developer", "position"], name="portfolio_project_position_unique"
            ),
        )

    def __str__(self) -> str:
        return self.title


