"""ORM models. Add models only when a backlog item needs them, and commit the
migration generated by ``python manage.py makemigrations`` with the change."""

import uuid

from django.db import models
from django.db.models import Q


class PaymentModel(models.Model):
    """A Stripe test-mode payment (#7). ``project_id`` and ``offer_version_id``
    become foreign keys when the Project (#3) and Offer (#6) models exist."""

    class Type(models.TextChoices):
        DEPOSIT = "deposit"

    class Status(models.TextChoices):
        PENDING = "pending"
        COMPLETED = "completed"
        FAILED = "failed"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    project_id = models.BigIntegerField(db_index=True)
    offer_version_id = models.BigIntegerField()
    type = models.CharField(max_length=16, choices=Type.choices)
    amount_cents = models.PositiveIntegerField()
    currency = models.CharField(max_length=3)
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.PENDING)
    checkout_session_id = models.CharField(max_length=255, unique=True, null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    completed_at = models.DateTimeField(null=True, blank=True)
    deleted_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = "payment"
        constraints = (
            models.UniqueConstraint(
                fields=["project_id"],
                condition=Q(type="deposit", status="completed", deleted_at__isnull=True),
                name="payment_one_completed_deposit_per_project",
            ),
            models.CheckConstraint(condition=Q(amount_cents__gt=0), name="payment_amount_positive"),
            models.CheckConstraint(condition=Q(currency="cad"), name="payment_currency_cad"),
        )

    def __str__(self) -> str:
        return f"{self.type} {self.id} ({self.status})"


class StripeEventModel(models.Model):
    """Every processed Stripe event id, so a redelivered event changes nothing."""

    event_id = models.CharField(max_length=255, primary_key=True)
    type = models.CharField(max_length=100)
    received_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "stripe_event"

    def __str__(self) -> str:
        return self.event_id
