"""Local private storage, the first ``FileStorage`` adapter (#3).

Files live under ``PRIVATE_MEDIA_ROOT``, which is git-ignored and served by
nothing: the only way out is ``DownloadDocument``, which checks the link and
the reader's access first. Keys are generated by the use case, never taken
from an uploaded filename, and are checked here so no key can leave the root.
"""

import re
from pathlib import Path

_KEY = re.compile(r"^[0-9a-f]{32}$")


class LocalPrivateStorage:
    def __init__(self, root: Path) -> None:
        self._root = root

    def _path(self, key: str) -> Path:
        if not _KEY.match(key):
            raise ValueError("Storage keys are 32 lowercase hex characters.")
        return self._root / key[:2] / key

    def save(self, key: str, content: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("xb") as file:  # never overwrite
            file.write(content)

    def read(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)
